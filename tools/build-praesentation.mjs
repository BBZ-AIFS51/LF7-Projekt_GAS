// Packs praesentation/index.html into ONE file that runs without the rest of
// the repo: every local <script src> (three.js, enclosure data, js/*.js) and
// the font stylesheet are inlined. Handy for a USB stick or an e-mail.
// No dependencies.
//
// Usage (from the repo root):
//   node tools/build-praesentation.mjs      -> praesentation/GAS-Praesentation.html
//
// Run it again whenever praesentation/ or docs/viewer/ changes.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const DIR = join(ROOT, 'praesentation');
const OUT = join(DIR, 'GAS-Praesentation.html');
const read = (rel) => readFileSync(join(DIR, rel), 'utf8');

let page = read('index.html');
let n = 0;
page = page.replace(/<script src="([^"]+)"><\/script>/g, (_, src) => {
  n++;
  return `<script>/* ${src} */\n${read(src).replace(/<\/script/gi, '<\\/script')}\n</script>`;
});
page = page.replace(/<link rel="stylesheet" href="([^"]+)">/g, (_, href) => { n++; return `<style>/* ${href} */\n${read(href)}</style>`; });
page = page.replace('<title>Projekt GAS – Präsentation</title>',
  '<title>Projekt GAS – Präsentation</title>\n<!-- Generated by tools/build-praesentation.mjs from praesentation/index.html - do not edit by hand. -->');
writeFileSync(OUT, page);
console.log(`${OUT}: ${n} files inlined, ${Math.round(page.length / 1024)} KB`);
