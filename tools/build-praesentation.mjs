// Packs praesentation/index.html into ONE file that runs without the rest of
// the repo: the 3D viewer (docs/viewer/index.html with three.min.js and
// enclosure.js inlined) goes into the iframe as srcdoc. Handy for a USB stick,
// an e-mail or a preview that only gets a single file. No dependencies.
//
// Usage (from the repo root):
//   node tools/build-praesentation.mjs      -> praesentation/GAS-Praesentation.html
//
// Run it again whenever praesentation/index.html or docs/viewer/ changes.

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const read = (...p) => readFileSync(join(ROOT, ...p), 'utf8');
const OUT = join(ROOT, 'praesentation', 'GAS-Praesentation.html');

function replaceOnce(text, from, to, what) {
  const n = text.split(from).length - 1;
  if (n !== 1) throw new Error(`${what}: expected exactly one match, found ${n}`);
  return text.replace(from, () => to);
}
const inlineScript = (code) => '<script>' + code.replace(/<\/script/gi, '<\\/script') + '</script>';

// the viewer as one document, always in ?shot mode (srcdoc has no URL query)
let viewer = read('docs', 'viewer', 'index.html');
viewer = replaceOnce(viewer, '<script src="three.min.js"></script>', inlineScript(read('docs', 'viewer', 'three.min.js')), 'three.min.js');
viewer = replaceOnce(viewer, '<script src="enclosure.js"></script>', inlineScript(read('docs', 'viewer', 'enclosure.js')), 'enclosure.js');
viewer = replaceOnce(viewer, "new URLSearchParams(location.search).has('shot')", 'true', 'shot mode');

const attr = viewer.replace(/&/g, '&amp;').replace(/"/g, '&quot;');
let page = read('praesentation', 'index.html');
page = replaceOnce(page, 'src="../docs/viewer/index.html?shot"', `srcdoc="${attr}"`, 'iframe');
page = replaceOnce(page, '<title>Projekt GAS – Präsentation</title>',
  '<title>Projekt GAS – Präsentation</title>\n<!-- Generated by tools/build-praesentation.mjs from praesentation/index.html - do not edit by hand. -->', 'title');

writeFileSync(OUT, page);
console.log(`${OUT} (${Math.round(page.length / 1024)} KB)`);
